"""Data model of a real-time system (vendored, read-only).

A *system* is a set of **flows**; each flow is an ordered chain of **tasks**
that are mapped onto **processors**. Tasks on the same processor are scheduled
by fixed priorities. This module is the data model used by the analysis and the
evaluation harness.

Priority convention
-------------------
A task's ``priority`` is a number; **a larger number means a higher priority**.
``higher_priority(t)`` returns the tasks on ``t``'s processor whose priority is
``>=`` ``t``'s priority, i.e. exactly the tasks that interfere with ``t``.

Do not edit this file.
"""

import math
import sys
from enum import Enum
from typing import List, Union


class SchedulerType(Enum):
    """Scheduling policy of a processor."""

    FP = "Fixed_Priority"
    EDF = "EDF"


class LinearSystem:
    """A distributed real-time system: a set of flows mapped onto processors."""

    def __init__(self):
        self.name = None
        self.flows: List["Flow"] = []
        self.processors: List["Processor"] = []

    def add_flows(self, *flows: "Flow") -> None:
        self.flows += flows
        for flow in flows:
            flow.system = self

    def add_procs(self, *procs: "Processor") -> None:
        for proc in procs:
            self.processors.append(proc)
            proc.system = self

    def apply(self, function):
        """Apply ``function`` to this system and return it."""
        function(self)
        return self

    @property
    def tasks(self) -> List["Task"]:
        """All tasks of the system, in flow order."""
        return [task for flow in self.flows for task in flow.tasks]

    def processor(self, name: str) -> Union["Processor", None]:
        return next((p for p in self.processors if p.name == name), None)

    def __getitem__(self, item):
        if isinstance(item, (int, slice)):
            return self.flows[item]
        if isinstance(item, str):
            match = [flow for flow in self.flows if flow.name == item]
            return match[0] if match else None
        return None

    def is_schedulable(self) -> bool:
        """True iff every flow meets its end-to-end deadline."""
        return all(flow.is_schedulable() for flow in self.flows)

    @property
    def utilization(self) -> float:
        """Mean processor utilization."""
        us = [proc.utilization for proc in self.processors]
        return sum(us) / len(us) if us else 0.0

    @property
    def max_utilization(self) -> float:
        us = [proc.utilization for proc in self.processors]
        return max(us) if us else 0.0

    @property
    def slack(self) -> float:
        """Minimum slack among all flows."""
        slacks = [flow.slack for flow in self.flows]
        return min(slacks) if slacks else sys.float_info.min

    @property
    def avg_flow_wcrt(self) -> float:
        wcrts = [flow.wcrt for flow in self.flows]
        return sum(wcrts) / len(wcrts) if wcrts else 0.0

    @property
    def hyperperiod(self):
        return math.lcm(*[f.period for f in self.flows])

    def __repr__(self) -> str:
        return "\n".join(str(flow) for flow in self.flows)


class Processor:
    """A processing element running fixed-priority scheduling."""

    def __init__(self, name: str, sched: SchedulerType = SchedulerType.FP, local: bool = True):
        self.name: str = name
        self.sched: SchedulerType = sched
        self.local: bool = local
        self.system: LinearSystem = None

    def __repr__(self) -> str:
        return f"{self.name}"

    @property
    def tasks(self) -> List["Task"]:
        """The tasks currently mapped onto this processor."""
        if not self.system:
            return []
        return [task for flow in self.system.flows for task in flow.tasks
                if task.processor == self]

    @property
    def utilization(self) -> float:
        return sum(task.wcet / task.period for task in self.tasks)


class Flow:
    """An ordered chain of tasks with a period and an end-to-end deadline."""

    def __init__(self, name: str, period: float, deadline: float, priority: int = None):
        self.system: LinearSystem = None
        self.name: str = name
        self.period: float = period
        self.deadline: float = deadline
        self.tasks: List["Task"] = []
        self.phase: float = 0
        self.priority: int = priority

    def add_tasks(self, *tasks: "Task") -> None:
        self.tasks += tasks
        for task in tasks:
            task.flow = self

    @property
    def wcrt(self) -> Union[float, None]:
        """End-to-end worst-case response time (of the last task)."""
        return self.tasks[-1].wcrt if self.tasks else None

    @property
    def slack(self) -> float:
        if self.wcrt:
            return (self.deadline - self.wcrt) / self.deadline
        return float("-inf")

    def predecessors(self, task: "Task") -> List["Task"]:
        i = self.tasks.index(task)
        return [self.tasks[i - 1]] if i > 0 else []

    def successors(self, task: "Task") -> List["Task"]:
        i = self.tasks.index(task)
        return [self.tasks[i + 1]] if i < len(self.tasks) - 1 else []

    def all_successors(self, task: "Task") -> List["Task"]:
        return self.tasks[self.tasks.index(task) + 1:]

    def is_schedulable(self) -> bool:
        return self.wcrt is not None and self.wcrt <= self.deadline

    def __getitem__(self, item):
        if isinstance(item, (int, slice)):
            return self.tasks[item]
        if isinstance(item, str):
            match = [task for task in self.tasks if task.name == item]
            return match[0] if match else None
        return None

    def __repr__(self) -> str:
        ts = " ".join(str(task) for task in self.tasks)
        return f"{self.period:.2f} : {ts} : {self.deadline:.2f})"


class TaskType(Enum):
    ACTIVITY = "Activity"
    OFFSET = "Offset"
    DELAY = "Delay"


class Task:
    """A single computation with a worst-case execution time.

    Attributes relevant to scheduling: ``wcet``, ``priority`` and
    ``processor``. ``period`` and ``jitter`` are derived (from the flow and
    from the predecessor's response time respectively).
    """

    def __init__(self, name: str, wcet: float, processor: Processor = None,
                 type: TaskType = TaskType.ACTIVITY, priority: int = 1,
                 bcet: float = 0, deadline: float = 0):
        self.name: str = name
        self.wcet: float = wcet
        self.processor: Processor = processor
        self.type: TaskType = type
        self.priority: int = priority
        self.deadline: float = deadline
        self.bcet: float = bcet
        self.wcrt: float = None
        self.flow: Flow = None

    def __repr__(self) -> str:
        return f"{self.processor.name if self.processor else None}({self.utilization:.2f})"

    @property
    def utilization(self) -> float:
        return self.wcet / self.period

    @property
    def period(self) -> float:
        return self.flow.period if self.flow else None

    @property
    def sched(self) -> SchedulerType:
        return self.processor.sched if self.processor else None

    @property
    def successors(self) -> List["Task"]:
        return self.flow.successors(self) if self.flow else []

    @property
    def predecessors(self) -> List["Task"]:
        return self.flow.predecessors(self) if self.flow else []

    @property
    def is_last(self) -> bool:
        return len(self.successors) == 0

    @property
    def all_successors(self) -> List["Task"]:
        return self.flow.all_successors(self) if self.flow else []

    @property
    def jitter(self) -> float:
        """Release jitter: the maximum response time of the predecessors."""
        wcrts = [t.wcrt for t in self.predecessors]
        return max(wcrts) if wcrts else 0


def higher_priority(task: Task) -> List[Task]:
    """Tasks on ``task``'s processor with priority ``>=`` ``task``'s priority.

    These are exactly the tasks that can interfere with ``task`` under
    fixed-priority scheduling (a larger priority number means higher priority).
    """
    return [t for t in task.processor.tasks
            if t.priority >= task.priority and t != task]


def init_wcrt(system: LinearSystem) -> None:
    """Seed each task's WCRT with its own WCET plus the flow predecessors'."""
    for flow in system.flows:
        tasks = flow.tasks
        for i, task in enumerate(tasks):
            task.wcrt = task.wcet
            if i > 0:
                task.wcrt += tasks[i - 1].wcrt


def reset_wcrt(system: LinearSystem) -> None:
    for task in system.tasks:
        task.wcrt = None


def calculate_priorities(system: LinearSystem) -> bool:
    """Assign per-processor priorities from the tasks' ``deadline`` attribute.

    Tasks are sorted by decreasing ``deadline`` and receive priorities
    ``1..n``, so the smallest deadline gets the largest (highest) priority.
    """
    changed = False
    for processor in system.processors:
        tasks = sorted(processor.tasks, key=lambda t: t.deadline, reverse=True)
        for i, task in enumerate(tasks):
            if not changed and task.priority != i + 1:
                changed = True
            task.priority = i + 1
    return changed


def normalize_priorities(system: LinearSystem) -> None:
    """Scale every priority into ``(0, 1]`` while preserving the ordering."""
    max_priority = max(t.priority for t in system.tasks)
    for t in system.tasks:
        t.priority = t.priority / max_priority


def clear_assignment(system: LinearSystem) -> None:
    for t in system.tasks:
        t.priority = 1
        t.deadline = None


class LimitFactorReachedException(Exception):
    def __init__(self, task, response_time, limit):
        self.task = task
        self.response_time = response_time
        self.limit = limit
        super().__init__(
            f"response time of {task.name} (R={response_time}) reached the "
            f"limit (limit={limit})")
