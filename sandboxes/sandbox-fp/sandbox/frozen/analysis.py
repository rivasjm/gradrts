"""Holistic Fixed-Priority analysis (vendored, read-only).

This is the response-time analysis used to decide whether a system is
schedulable: it computes the worst-case response times (WCRTs) that the rest of
the lab uses as the reference. It is **approximate, not exact**: it does not
compute the true worst-case behaviour of the system. It is nevertheless *the
reference* here -- "schedulable" means exactly "this analysis says so", and the
reference ceiling is defined under that same test.

The analysis is *holistic*: because tasks in a flow execute on different
processors, the release jitter of a task equals the worst-case response time of
its predecessor. This couples the processors and is solved by the outer
convergence loop.

Do not edit this file.
"""

import math
import time

from .model import init_wcrt, reset_wcrt, higher_priority


class HolisticFPAnalysis:
    """Compute worst-case response times of an FP system (in ``task.wcrt``).

    Parameters
    ----------
    limit_factor:
        A provisional response time above ``deadline * limit_factor`` aborts
        the analysis for that task; larger values trade speed for precision.
    reset:
        If True, ``task.wcrt`` is reset to ``None`` before the analysis.
    verbose:
        Print the fixed-point iterations.
    max_time:
        Optional wall-clock budget (seconds); exceeding it behaves like
        reaching the response-time limit.
    prune_over_utilized:
        Shortcut for processors whose utilization is ``>= 1`` (they are never
        schedulable under fixed priorities).
    """

    def __init__(self, limit_factor=10, reset=False, verbose=False, max_time=None,
                 prune_over_utilized=False):
        self.limit_factor = limit_factor
        self.reset = reset
        self.verbose = verbose
        self.max_time = max_time
        self.prune_over_utilized = prune_over_utilized
        self._start = None

    def __call__(self, system):
        return self.apply(system)

    def _timeout(self) -> bool:
        return self.max_time is not None and time.perf_counter() - self._start > self.max_time

    def _abort(self, system, task):
        """Behave as if ``task`` reached its response-time limit."""
        if self.reset:
            reset_wcrt(system)
        else:
            for t in task.all_successors:
                t.wcrt = task.wcrt

    def apply(self, system) -> None:
        init_wcrt(system)
        self._start = time.perf_counter()

        # A processor at or above full utilization cannot schedule its tasks
        # under fixed priorities and its busy period never closes, so skip the
        # (potentially very slow) fixed-point loop and saturate the WCRTs.
        if self.prune_over_utilized and any(p.utilization >= 1.0 for p in system.processors):
            if self.reset:
                reset_wcrt(system)
            else:
                for task in system.tasks:
                    task.wcrt = (self.limit_factor + 1) * task.flow.deadline
            return

        wcrts = [t.wcrt for t in system.tasks]
        wcrts_prev = [0 for _ in system.tasks]

        while wcrts != wcrts_prev:  # outer: global convergence of the WCRTs
            wcrts_prev = wcrts[:]

            for task in system.tasks:
                hp = higher_priority(task)
                limit = task.flow.deadline * self.limit_factor

                p = 1
                while True:  # busy-period jobs
                    w_prev = 0
                    w = p * task.wcet

                    while w != w_prev:  # inner fixed point
                        w_prev = w
                        w = sum(math.ceil((t.jitter + w) / t.period) * t.wcet
                                for t in hp) + p * task.wcet
                        r = w - (p - 1) * task.period + task.jitter

                        if self.verbose:
                            print(f"{task.name} p={p} w={w:.3f} wprev={w_prev:.3f} r={r:.3f}")
                        if r > task.wcrt:
                            task.wcrt = r
                        if r > limit or self._timeout():
                            self._abort(system, task)
                            return

                    if w <= p * task.period:
                        break  # busy period closed

                    p += 1

            wcrts = [t.wcrt for t in system.tasks]
