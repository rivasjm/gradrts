"""Trivial reference assignments (vendored, read-only).

These are not meant to be strong: they give the evaluation a floor to compare
against. ``pd`` is a proportional-deadline baseline; ``random_assign`` is a
uniform random ordering.

Do not edit this file.
"""

import random as _random

from .model import calculate_priorities, normalize_priorities


def pd_assign(system) -> None:
    """Proportional deadlines: local deadline proportional to each task's WCET.

    Sets each task's ``deadline`` to ``wcet * flow.deadline / sum(wcet)`` and
    then assigns deadline-monotonic priorities per processor (smallest deadline
    gets the highest priority number).
    """
    for flow in system.flows:
        total = sum(task.wcet for task in flow.tasks)
        for task in flow.tasks:
            task.deadline = task.wcet * flow.deadline / total
    calculate_priorities(system)
    normalize_priorities(system)


def random_assign(system, seed: int = 0) -> None:
    """Assign a uniformly random priority permutation (higher number = higher)."""
    tasks = system.tasks
    order = list(range(len(tasks)))
    _random.Random(seed).shuffle(order)
    for rank, i in enumerate(order):
        tasks[i].priority = rank + 1
