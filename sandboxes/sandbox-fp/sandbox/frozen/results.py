"""Result records and the derived leaderboard (read-only infrastructure).

Every evaluated method -- including the ``brute-force`` reference -- is stored
as a JSON *record* with exactly the same schema. The leaderboard is never
written by hand: it is derived from all records found under ``results/``.

A record looks like::

    {
      "method": "brute-force" | "gdpa" | "<algorithm>",
      "pool": "15", "seed": 42, "size": 15,
      "population": 50, "n_levels": 20, "utilizations": [...],
      "per_level": [50, 50, ...],   # schedulable per utilization level
      "per_level_time": [0.01, ...],      # mean s/instance per level (finished only)
      "per_level_finished": [50, 50, ...], # instances finished (no timeout/error)
      "total": 927, "instances": 1000, "ratio": 0.927,
      "mean_time": 0.0, "total_time": 0.0, "timeouts": 0, "errors": [],
      "generated": "2026-10-01T...", "identity": {...}   # optional
    }

Execution time is part of the record (``mean_time`` / ``total_time``, seconds
per instance and per sweep) and is reported in the leaderboard: a slow method is
not an acceptable method. A reference record may report ``mean_time = null``
when its runtime is not comparable.

The reference record (whose method depends on the pool, see
``frozen.pool.REFERENCE_METHOD``) additionally carries ``per_system`` (the
per-instance schedulability matrix) so the gap can be derived for partial
sweeps. That field is optional and additive; the comparable fields are identical
for every method.

Do not edit this file.
"""

import json
import os
import re
from datetime import datetime

from . import pool as _pool


def slug(name):
    """Filename-safe version of a method name."""
    return re.sub(r"[^0-9A-Za-z._-]+", "_", str(name)).strip("_") or "method"


def make_record(method, pool_label, seed, size, population, utilizations,
                per_level, mean_time=0.0, total_time=0.0, timeouts=0, errors=None,
                identity=None, per_system=None, per_level_time=None,
                per_level_finished=None):
    """Build a canonical record. ``mean_time``/``total_time`` may be ``None``."""
    utilizations = [float(u) for u in utilizations]
    per_level = [int(x) for x in per_level]
    n_levels = len(utilizations)
    instances = population * n_levels
    total = sum(per_level)
    record = {
        "method": method,
        "pool": pool_label,
        "seed": int(seed),
        "size": int(size),
        "population": int(population),
        "n_levels": n_levels,
        "utilizations": utilizations,
        "per_level": per_level,
        "total": total,
        "instances": instances,
        "ratio": total / instances if instances else 0.0,
        "mean_time": None if mean_time is None else float(mean_time),
        "total_time": None if total_time is None else float(total_time),
        "timeouts": int(timeouts),
        "errors": list(errors or []),
        "generated": datetime.now().isoformat(timespec="seconds"),
    }
    if per_level_time is not None:
        record["per_level_time"] = [float(t) for t in per_level_time]
    if per_level_finished is not None:
        record["per_level_finished"] = [int(f) for f in per_level_finished]
    if identity:
        record["identity"] = identity
    if per_system is not None:
        record["per_system"] = per_system
    return record


def records_from_report(report, pool_label, identity=None):
    """Turn a ``harness.evaluate`` report into one record per method."""
    return [
        make_record(name, pool_label, report["seed"], report["size"],
                    report["population"], report["utilizations"],
                    method["per_level"], method["mean_time"], method["total_time"],
                    method["timeouts"], method["errors"], identity,
                    per_system=method.get("per_system"),
                    per_level_time=method.get("per_level_time"),
                    per_level_finished=method.get("per_level_finished"))
        for name, method in report["methods"].items()
    ]


def result_path(results_dir, record):
    return os.path.join(results_dir, record["pool"], slug(record["method"]) + ".json")


def save(results_dir, record):
    """Write (overwrite) a record under ``results/<pool>/<method>.json``."""
    path = result_path(results_dir, record)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as fh:
        json.dump(record, fh, indent=1)
    return path


def load_all(results_dir):
    """Load every record under ``results/`` (malformed files are skipped)."""
    records = []
    for root, _dirs, files in os.walk(results_dir):
        for name in sorted(files):
            if not name.endswith(".json"):
                continue
            try:
                with open(os.path.join(root, name)) as fh:
                    record = json.load(fh)
            except (OSError, ValueError):
                continue
            if isinstance(record, dict) and "method" in record:
                records.append(record)
    return records


def group_key(record):
    """Identity of a sweep: records only compete within the same key."""
    return (record.get("pool"), record.get("seed"), record.get("size"),
            record.get("population"), record.get("n_levels"),
            tuple(round(float(u), 9) for u in record.get("utilizations", [])))


def summary_key(record):
    return (record.get("pool"), record.get("seed"), record.get("size"),
            record.get("population"), record.get("n_levels"))


def _utils(record):
    return tuple(round(float(u), 9) for u in record.get("utilizations", []))


def find_reference(records, key):
    """Return ``(total, per_level_counts)`` of the reference covering ``key``.

    The reference method is per pool (``frozen.pool.REFERENCE_METHOD``): an exact
    record wins; otherwise its ``per_system`` matrix is used to derive the counts
    for a partial sweep (a prefix of systems/levels). Returns ``None`` when the
    pool has no reference or none covers ``key``.
    """
    pool_label, seed, size, population, n_levels, utils = key
    reference_method = _pool.REFERENCE_METHOD.get(pool_label)
    if reference_method is None:
        return None
    exact = None
    derived = None
    for record in records:
        if record.get("method") != reference_method:
            continue
        if (record.get("pool"), record.get("seed"), record.get("size")) != (pool_label, seed, size):
            continue
        if _utils(record)[:n_levels] != utils[:n_levels]:
            continue
        r_pop = int(record.get("population", 0))
        r_lev = int(record.get("n_levels", 0))
        if r_pop < population or r_lev < n_levels:
            continue
        if r_pop == population and r_lev == n_levels and exact is None:
            exact = (int(record["total"]), [int(x) for x in record["per_level"]])
        elif record.get("per_system") and derived is None:
            counts = [sum(record["per_system"][i][:population]) for i in range(n_levels)]
            derived = (sum(counts), counts)
    return exact or derived


def leaderboard_rows(records):
    """Merge every record into comparable rows (one per method and sweep)."""
    groups = {}
    for record in records:
        groups.setdefault(group_key(record), []).append(record)

    rows = []
    for key in sorted(groups, key=lambda k: (str(k[0]), k[1] or 0, k[3] or 0, k[4] or 0)):
        reference = find_reference(records, key)
        for record in sorted(groups[key], key=lambda r: (-int(r.get("total", 0)), str(r.get("method")))):
            total = int(record.get("total", 0))
            instances = int(record.get("instances", 0))
            identity = record.get("identity") or {}
            rows.append({
                "pool": key[0], "seed": key[1], "size": key[2],
                "population": key[3], "n_levels": key[4],
                "method": record.get("method"),
                "schedulable": total,
                "instances": instances,
                "ratio": total / instances if instances else 0.0,
                "reference": reference[0] if reference else None,
                "gap": (reference[0] - total) if reference else None,
                "mean_time": record.get("mean_time"),
                "total_time": record.get("total_time"),
                "timeouts": record.get("timeouts"),
                "generated": record.get("generated"),
                "model": identity.get("model", ""),
                "utilizations": list(record.get("utilizations", [])),
                "per_level": list(record.get("per_level", [])),
                "reference_per_level": reference[1] if reference else None,
            })
    return rows


CSV_COLUMNS = ["pool", "seed", "population", "n_levels", "method", "schedulable",
               "instances", "ratio", "reference", "gap", "mean_time", "total_time",
               "timeouts", "model", "generated"]


def _num(value, fmt):
    return "" if value is None else fmt.format(value)


def write_leaderboard_csv(rows, path):
    import csv
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", newline="") as fh:
        writer = csv.writer(fh)
        writer.writerow(CSV_COLUMNS)
        for row in rows:
            writer.writerow([
                row["pool"], row["seed"], row["population"], row["n_levels"],
                row["method"], row["schedulable"], row["instances"],
                _num(row["ratio"], "{:.6f}"),
                _num(row["reference"], "{}"),
                _num(row["gap"], "{}"),
                _num(row["mean_time"], "{:.6f}"),
                _num(row["total_time"], "{:.6f}"),
                row["timeouts"], row["model"], row["generated"],
            ])
    return path


def leaderboard_path(results_dir, pool_label):
    return os.path.join(results_dir, str(pool_label), "leaderboard.csv")


def write_leaderboards(rows, results_dir):
    """Write one leaderboard CSV per pool; return the list of paths."""
    pools = sorted({row["pool"] for row in rows if row.get("pool")})
    paths = []
    for pool_label in pools:
        pool_rows = [row for row in rows if row["pool"] == pool_label]
        paths.append(write_leaderboard_csv(pool_rows, leaderboard_path(results_dir, pool_label)))
    return paths
