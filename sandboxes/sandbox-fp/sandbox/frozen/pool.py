"""Deterministic system pools (vendored, read-only).

Two *balanced* pools ship with the sandbox, both built from the same fixed
seed (42), 50 systems each, and swept over the same utilization levels:

``15``  5 flows x 3 tasks x 3 processors  (15 tasks).
``25``  5 flows x 5 tasks x 5 processors  (25 tasks).

Task utilizations are drawn globally by UUNIFAST and tasks are assigned
round-robin (highest utilization first) so every processor gets the same number
of tasks. The utilization sweep is applied later, per instance, with
``set_utilization``: it rescales the tasks of each processor so that *every*
processor reaches exactly the requested utilization ``u``.

Both pools are objectives (there is no development/validation split). Their
reference method
(shown as the ceiling in the leaderboard) differs because an exhaustive search
is only tractable for ``15``:

``REFERENCE_METHOD``
    ``{"15": "brute-force", "25": "gdpa"}``.

Do not edit this file.
"""

from math import exp, log, pow
from random import Random

from .model import Flow, LinearSystem, Processor, SchedulerType, Task

SIZES = {15: (5, 3, 3), 25: (5, 5, 5)}   # size -> (flows, tasks-per-flow, processors)
POOLS = (15, 25)                         # the sizes shipped
SEED = 42
POPULATION = 50

# The method whose record is the ceiling of each pool. For 25 an exhaustive
# search is intractable (5!^5), so the strong reference gdpa is used instead.
REFERENCE_METHOD = {"15": "brute-force", "25": "gdpa"}
BRUTE_FORCE_METHOD = "brute-force"

DEADLINE_FACTOR_MIN = 0.5
DEADLINE_FACTOR_MAX = 1.0
PERIOD_MIN = 100
PERIOD_MAX = 1000
BASE_UTILIZATION = 0.5           # utilization the pool is *generated* at

# Utilization sweep: 20 levels in [0.5, 0.9].
UTILIZATIONS = [0.5 + (0.9 - 0.5) * i / 19 for i in range(20)]


def uunifast(random: Random, n_tasks: int, utilization: float):
    """Draw ``n_tasks`` utilizations summing to ``utilization`` (UUNIFAST)."""
    sum_u = utilization
    us = []
    for i in range(1, n_tasks):
        next_sum_u = sum_u * pow(random.random(), 1 / (n_tasks - i))
        us.append(sum_u - next_sum_u)
        sum_u = next_sum_u
    us.append(sum_u)
    return us


def log_uniform(random: Random, lowest: float, highest: float) -> float:
    return exp(random.uniform(log(lowest), log(highest)))


def assign_balanced(tasks, procs):
    """Round-robin assignment by decreasing utilization (no randomness)."""
    order = sorted(tasks, key=lambda task: task.utilization, reverse=True)
    for i, task in enumerate(order):
        task.processor = procs[i % len(procs)]


def generate_system(random: Random, n_flows, n_tasks, n_procs, utilization, sched,
                    period_min=100, period_max=100000, deadline_factor_min=0.5,
                    deadline_factor_max=1, balanced=False) -> LinearSystem:
    """Generate one random system with a balanced mapping."""
    system = LinearSystem()
    procs = [Processor(name=f"proc{i}", sched=sched) for i in range(n_procs)]
    system.add_procs(*procs)

    for f in range(n_flows):
        period = log_uniform(random, period_min, period_max)
        deadline = random.uniform(
            period * n_tasks * deadline_factor_min,
            period * n_tasks * deadline_factor_max)
        flow = Flow(name=f"flow{f}", period=period, deadline=deadline)
        tasks = [Task(name=f"task{f}_{t}", wcet=0) for t in range(n_tasks)]
        flow.add_tasks(*tasks)
        system.add_flows(flow)

    tasks = system.tasks
    us = uunifast(random, len(tasks), utilization * n_procs)
    for task, u in zip(tasks, us):
        task.wcet = u * task.period

    # This sandbox only ships the balanced mapping.
    assign_balanced(tasks, procs)

    return system


def get_systems(seed: int = SEED, size: int = 15, population: int = POPULATION):
    """Return a fresh list of ``population`` pristine systems of the given size.

    A single ``Random(seed)`` instance drives the whole population, so the same
    seed always yields the same pool.
    """
    if size not in SIZES:
        raise ValueError(f"unknown size {size!r}, use one of {sorted(SIZES)}")
    n_flows, n_tasks, n_procs = SIZES[size]

    rnd = Random(seed)
    systems = []
    for i in range(population):
        system = generate_system(
            rnd, n_flows=n_flows, n_tasks=n_tasks, n_procs=n_procs,
            utilization=BASE_UTILIZATION, sched=SchedulerType.FP,
            period_min=PERIOD_MIN, period_max=PERIOD_MAX,
            deadline_factor_min=DEADLINE_FACTOR_MIN,
            deadline_factor_max=DEADLINE_FACTOR_MAX, balanced=True)
        system.name = str(i)
        systems.append(system)
    return systems


def set_processor_utilization(processor: Processor, utilization: float) -> None:
    """Rescale every task of ``processor`` so the processor reaches ``u``."""
    tasks = processor.tasks
    if not tasks:
        return
    factor = utilization / processor.utilization
    for task in tasks:
        task.wcet *= factor


def set_utilization(system: LinearSystem, utilization: float) -> None:
    """Set every processor of ``system`` to the given utilization."""
    for proc in system.processors:
        set_processor_utilization(proc, utilization)
