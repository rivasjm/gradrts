"""Per-pool chart (read-only): schedulable systems and mean time, stacked.

A single figure with two panels: the top one shows the number of schedulable
systems and the bottom one the mean time per instance, both versus utilization,
one line per method. Refreshed as a sweep progresses. Uses matplotlib (a
required dependency of this sandbox; install ``requirements.txt``).

Do not edit this file.
"""


def _pyplot():
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except Exception as exc:  # pragma: no cover - depends on the environment
        raise RuntimeError(
            "matplotlib is required to draw charts; run "
            "`pip install -r requirements.txt` (or use --no-plot)") from exc
    return plt


def _color_map(names):
    """Deterministic color per method name (same color in both panels).

    Colors are assigned by the sorted name order, so a method keeps its color
    whether or not other methods are plotted in a given panel.
    """
    import matplotlib
    cmap = matplotlib.colormaps["tab10"]
    order = sorted(names)
    return {name: cmap(i % 10) for i, name in enumerate(order)}


def write_pool_chart(path, title, utilizations, schedulable, times, log=True):
    """Render a 2x1 figure to ``path`` (PNG).

    ``schedulable`` and ``times`` are ``{method: [value per level]}`` dicts; the
    top panel plots schedulable systems and the bottom one the mean time per
    instance (log scale when ``log``). A method keeps the same color in both
    panels; a panel only draws the methods it has data for, but the color of a
    given method never changes.
    """
    plt = _pyplot()
    floor = 1e-9
    fig, (ax_top, ax_bottom) = plt.subplots(2, 1, figsize=(5.6, 6.2),
                                            sharex=True)

    colors = _color_map(set(schedulable) | set(times))

    for name, counts in schedulable.items():
        ax_top.plot(utilizations, counts, marker="o", linewidth=1.2,
                    color=colors[name], label=name)
    ax_top.set_ylabel("schedulable systems")
    ax_top.grid(True, alpha=0.3)
    ax_top.legend(fontsize=7, ncol=2)

    for name, t in times.items():
        if not t:
            continue
        ax_bottom.plot(utilizations[:len(t)], [max(x, floor) for x in t],
                       marker="o", linewidth=1.2, color=colors[name], label=name)
    if log:
        ax_bottom.set_yscale("log")
    ax_bottom.set_xlabel("utilization")
    ax_bottom.set_ylabel("mean time per instance (s)")
    ax_bottom.grid(True, alpha=0.3, which="both")
    ax_bottom.legend(fontsize=7, ncol=2)

    fig.suptitle(title, fontsize=10)
    fig.tight_layout(rect=(0, 0, 1, 0.97))
    fig.savefig(path, dpi=130)
    plt.close(fig)
    return path
