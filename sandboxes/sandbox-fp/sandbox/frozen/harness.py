"""Evaluation harness (read-only).

Protocol:

1. Take the pristine pool for a given size/seed.
2. For every utilization level and every system, clone the system, set every
   processor to that level and let the candidate algorithm assign **priorities**.
3. Judge the resulting assignment with :class:`frozen.analysis.HolisticFPAnalysis`
   (``limit_factor=1``) and count the system as schedulable iff every flow meets
   its end-to-end deadline.

The evaluation can run sequentially or over a process pool (``workers``); it can
dump raw per-instance records incrementally (``raw_path``) and call a callback
every time a utilization level completes (``on_level``), so results and plots can
be refreshed as the sweep progresses.

An algorithm is a callable ``algorithm(system) -> None`` that mutates each
``task.priority`` (a larger number means higher priority). Returning a sequence
of priorities in ``system.tasks`` order is also accepted. The mapping of tasks
to processors is fixed and must not be changed.

Do not edit this file.
"""

import contextlib
import json
import multiprocessing as mp
import os
import pickle
import signal
import time
from copy import deepcopy
from functools import partial

from . import pool as _pool
from .analysis import HolisticFPAnalysis


class Timeout(Exception):
    pass


def _raise_timeout(signum, frame):
    raise Timeout()


@contextlib.contextmanager
def time_limit(seconds):
    """Wall-clock limit for the enclosed block (SIGALRM based, Unix only)."""
    if not seconds or not hasattr(signal, "SIGALRM"):
        yield
        return
    old = signal.signal(signal.SIGALRM, _raise_timeout)
    signal.setitimer(signal.ITIMER_REAL, seconds)
    try:
        yield
    finally:
        signal.setitimer(signal.ITIMER_REAL, 0)
        signal.signal(signal.SIGALRM, old)


def is_schedulable(system) -> bool:
    """Run the Holistic FP analysis and report end-to-end schedulability."""
    HolisticFPAnalysis(limit_factor=1, reset=True).apply(system)
    return system.is_schedulable()


def _apply_result(system, result):
    """Accept either an in-place mutation or a returned priority sequence."""
    if result is None:
        return
    tasks = system.tasks
    if len(result) != len(tasks):
        raise ValueError(f"returned {len(result)} priorities for {len(tasks)} tasks")
    for task, prio in zip(tasks, result):
        task.priority = prio


def run_algorithm(algorithm, system, timeout=None):
    """Run ``algorithm`` on ``system``.

    Returns ``(seconds, status, message)`` where status is one of
    ``"ok"``, ``"timeout"`` or ``"error"``.
    """
    start = time.perf_counter()
    try:
        with time_limit(timeout):
            result = algorithm(system)
        _apply_result(system, result)
    except Timeout:
        return time.perf_counter() - start, "timeout", "exceeded time budget"
    except Exception as exc:  # keep the sweep alive and surface the message
        return time.perf_counter() - start, "error", f"{type(exc).__name__}: {exc}"
    return time.perf_counter() - start, "ok", ""


def _evaluate_instance(task, algorithms, timeout):
    """Run every algorithm on one ``(level, utilization, base system)`` instance."""
    ui, u, base, si = task
    work = deepcopy(base)
    _pool.set_utilization(work, u)
    out = {}
    for name, algorithm in algorithms.items():
        system = deepcopy(work)
        seconds, status, message = run_algorithm(algorithm, system, timeout)
        schedulable = is_schedulable(system) if status == "ok" else False
        out[name] = (schedulable, seconds, status, message)
    return ui, si, out


def _picklable(obj) -> bool:
    try:
        pickle.dumps(obj)
        return True
    except Exception:
        return False


def _write_json(path, records):
    """Atomically replace ``path`` with ``records`` (so partial runs survive)."""
    tmp = f"{path}.tmp"
    with open(tmp, "w") as fh:
        json.dump(records, fh)
    os.replace(tmp, path)


def aggregate(raw_records, names, population, utilizations, collect_per_system=False):
    """Turn raw per-instance records into the report structure.

    Per method and level it reports the schedulable count (``per_level``), the
    mean time over the instances that finished (``per_level_time``) and how many
    finished without timeout/error (``per_level_finished``).
    """
    n_levels = len(utilizations)
    per_level = {name: [0] * n_levels for name in names}
    per_level_time = {name: [0.0] * n_levels for name in names}
    per_level_finished = {name: [0] * n_levels for name in names}
    per_system = {name: [[False] * population for _ in utilizations] for name in names}
    total_time = {name: 0.0 for name in names}
    timeouts = {name: 0 for name in names}
    errors = {name: [] for name in names}

    for r in raw_records:
        name = r["method"]
        if name not in per_level:
            continue
        ui, si = r["level"], r["system"]
        total_time[name] += r.get("time") or 0.0
        per_level_time[name][ui] += r.get("time") or 0.0
        if r["status"] == "ok":
            per_level_finished[name][ui] += 1
        if r["status"] == "timeout":
            timeouts[name] += 1
        elif r["status"] == "error":
            if len(errors[name]) < 5:
                errors[name].append(f"u={r['u']:.3f} sys={si}: {r.get('message', '')}")
        elif r["schedulable"]:
            per_level[name][ui] += 1
        per_system[name][ui][si] = bool(r["schedulable"])

    instances = population * n_levels
    methods = {}
    for name in names:
        mean_level_time = [
            per_level_time[name][ui] / per_level_finished[name][ui]
            if per_level_finished[name][ui] else 0.0
            for ui in range(n_levels)
        ]
        methods[name] = {
            "per_level": per_level[name],
            "per_level_time": mean_level_time,
            "per_level_finished": per_level_finished[name],
            "total": sum(per_level[name]),
            "mean_time": total_time[name] / instances if instances else 0.0,
            "total_time": total_time[name],
            "timeouts": timeouts[name],
            "errors": errors[name],
        }
        if collect_per_system:
            methods[name]["per_system"] = per_system[name]
    return methods


def evaluate(algorithms, seed=_pool.SEED, size=15, population=_pool.POPULATION,
             utilizations=None, timeout=None, verbose=False, collect_per_system=False,
             workers=1, raw_path=None, on_level=None):
    """Evaluate ``{name: algorithm}`` over the pool swept by utilization.

    Parameters
    ----------
    workers:
        Number of worker processes (``1`` = sequential). When ``> 1`` and the
        algorithms are picklable, instances run over a process pool; otherwise
        it falls back to sequential with a warning.
    raw_path:
        If given, the raw per-instance records are written (atomically) there
        every time a utilization level completes.
    on_level:
        Called in the main process as ``on_level(raw_records, finished_levels)``
        every time a level completes, so the caller can refresh results/plots.

    Returns the same report as before: per method, the schedulable count at every
    utilization level, total, mean run time, timeouts and errors (plus
    ``per_system`` when requested).
    """
    utilizations = list(utilizations) if utilizations is not None else list(_pool.UTILIZATIONS)
    systems = _pool.get_systems(seed=seed, size=size, population=population)
    names = list(algorithms)
    n_levels = len(utilizations)
    n_systems = len(systems)
    instances = n_systems * n_levels

    tasks = [(ui, u, base, si)
             for ui, u in enumerate(utilizations)
             for si, base in enumerate(systems)]

    raw = []
    level_done = [0] * n_levels
    finished_levels = []
    done = 0

    def handle(ui, si, out):
        nonlocal done
        done += 1
        for name, (sched, seconds, status, message) in out.items():
            raw.append({
                "level": ui, "u": utilizations[ui], "system": si, "method": name,
                "schedulable": bool(sched), "status": status,
                "timeout": status == "timeout",
                "time": None if status == "timeout" else seconds,
                "message": message if status == "error" else "",
            })
        level_done[ui] += 1
        if level_done[ui] == n_systems:
            finished_levels.append(ui)
            if verbose:
                methods = aggregate(raw, names, n_systems, utilizations)
                done_str = " ".join(f"{n}={methods[n]['total']}" for n in names)
                print(f"  u={utilizations[ui]:.3f} ({len(finished_levels)}/{n_levels}): "
                      f"{done_str}", flush=True)
            if raw_path:
                _write_json(raw_path, raw)
            if on_level:
                on_level(raw, sorted(finished_levels))

    worker = partial(_evaluate_instance, algorithms=algorithms, timeout=timeout)
    if workers and workers > 1 and not _picklable(worker):
        print(f"warning: algorithms are not picklable; ignoring --workers {workers}",
              flush=True)
        workers = 1

    if workers and workers > 1:
        ctx = mp.get_context("fork")
        with ctx.Pool(workers) as proc_pool:
            for ui, si, out in proc_pool.imap_unordered(worker, tasks, chunksize=1):
                handle(ui, si, out)
    else:
        for task in tasks:
            handle(*worker(task))

    if raw_path:
        _write_json(raw_path, raw)

    methods = aggregate(raw, names, n_systems, utilizations, collect_per_system)
    return {
        "seed": seed,
        "size": size,
        "population": population,
        "utilizations": utilizations,
        "instances": instances,
        "methods": methods,
    }
