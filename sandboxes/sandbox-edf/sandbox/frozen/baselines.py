"""Trivial reference assignments (vendored, read-only).

These are not meant to be strong: they give the evaluation a floor to compare
against. Under local EDF the optimisable parameter is each task's **local
deadline** (``task.deadline``), so these assign deadlines, not priorities.

Do not edit this file.
"""

import random as _random


def pd_assign(system) -> None:
    """Proportional deadlines: local deadline proportional to each task's WCET.

    Sets ``task.deadline = wcet * flow.deadline / sum(wcet)`` over the tasks of
    the flow. This is the proportional-deadline baseline of the paper group.
    """
    for flow in system.flows:
        total = sum(task.wcet for task in flow.tasks)
        for task in flow.tasks:
            task.deadline = task.wcet * flow.deadline / total


def random_assign(system, seed: int = 0) -> None:
    """Assign a uniformly random local deadline in ``(0, flow.deadline]``."""
    rng = _random.Random(seed)
    for task in system.tasks:
        task.deadline = rng.uniform(1e-6, task.flow.deadline)


def equal_assign(system) -> None:
    """Split each flow's deadline equally among its tasks."""
    for flow in system.flows:
        n = len(flow.tasks)
        for task in flow.tasks:
            task.deadline = flow.deadline / n
