"""Vectorization benchmark harness (read-only).

Goal of the lab: take the *scalar* holistic local-EDF analysis in
``frozen/analysis.py`` and produce an analysis that evaluates **many deadline
assignments at once** (a batch of ``K`` assignments), reproducing the same
worst-case response times but much faster.

This harness is the referee. For a set of *instances* (a system at a given
utilization) it builds ``K`` deterministic local-deadline assignments, computes
the reference WCRTs with the scalar analysis, and then calls the candidate's
``analyze(system, deadlines)`` so it can compare:

- **equivalence**: do the candidate WCRTs match the reference (within tolerance)?
- **speedup**: how much faster is one batched call than the ``K`` scalar calls?

An instance is a ``LinearSystem`` (mutable) whose processors are EDF. The
candidate must set the local deadlines of its tasks from the assignment matrix
``deadlines[j]`` and return the per-task WCRTs of that assignment, without
mutating the caller's systems across calls.

Do not edit this file.
"""

import time
from copy import deepcopy
from random import Random

from . import pool as _pool
from .analysis import HolisticLocalEDFAnalysis
from .model import reset_wcrt


# --- instance + assignment generation ---------------------------------------

def _default_assignments(system, k, seed):
    """Build ``k`` deterministic local-deadline assignments ``(k, n_tasks)``.

    A fixed, reproducible mix: proportional to WCET (``pd``), equal split,
    uniform random, and multiplicative perturbations of ``pd`` and of the flow
    deadline. This covers the interesting regimes (tight/loose local deadlines)
    without the candidate controlling the sample.
    """
    tasks = system.tasks
    n = len(tasks)
    rng = Random(seed)
    flows = system.flows

    def pd_vec():
        out = [0.0] * n
        for flow in flows:
            total = sum(t.wcet for t in flow.tasks)
            for i, t in enumerate(flow.tasks):
                out[tasks.index(t)] = t.wcet * flow.deadline / total
        return out

    def equal_vec():
        out = [0.0] * n
        for flow in flows:
            for t in flow.tasks:
                out[tasks.index(t)] = flow.deadline / len(flow.tasks)
        return out

    base = pd_vec()
    rows = [pd_vec(), equal_vec()]
    while len(rows) < k:
        mode = len(rows) % 3
        if mode == 0:                       # perturb pd
            rows.append([max(v * rng.uniform(0.4, 2.2), 1e-9) for v in base])
        elif mode == 1:                     # uniform random in (0, flow deadline]
            rows.append([rng.uniform(1e-9, tasks[i].flow.deadline) for i in range(n)])
        else:                               # random fraction of the flow deadline
            rows.append([tasks[i].flow.deadline * rng.uniform(0.05, 1.0)
                         for i in range(n)])
    return rows[:k]


def build_instances(population=25, levels=None, k=100, seed=_pool.SEED):
    """Return a deterministic list of instances.

    Each instance is ``{"name", "system", "utilization", "deadlines"}`` where
    ``deadlines`` is a ``(k, n_tasks)`` list of K assignments. ``population``
    systems are drawn across the utilization sweep; ``levels`` selects how many
    utilization levels to spread them over (default: all 20, one system per
    level, cycled).
    """
    utilizations = _pool.UTILIZATIONS
    if levels:
        utilizations = utilizations[:levels]
    systems = _pool.get_systems(seed=seed, population=max(population, levels or 1))
    instances = []
    for i in range(population):
        u = utilizations[i % len(utilizations)]
        system = deepcopy(systems[i % len(systems)])
        _pool.set_utilization(system, u)
        rng = Random(seed + i)
        deadlines = _default_assignments(system, k, seed + i)
        instances.append({
            "name": f"sys{i}-u{u:.3f}",
            "system": system,
            "utilization": u,
            "deadlines": deadlines,
        })
    return instances


# --- reference (scalar) analysis --------------------------------------------

def _scalar_wcrts(system, deadlines):
    """Run the scalar analysis once per assignment and return WCRTs ``(k, n)``."""
    tasks = system.tasks
    out = []
    for assignment in deadlines:
        for task, d in zip(tasks, assignment):
            task.deadline = d
        reset_wcrt(system)
        HolisticLocalEDFAnalysis(limit_factor=10, reset=True).apply(system)
        out.append([float("inf") if t.wcrt is None else t.wcrt for t in tasks])
    return out


def reference_wcrts(instances, collect_time=False):
    """Reference WCRTs for every instance (scalar analysis, one per assignment)."""
    refs = []
    for inst in instances:
        system = deepcopy(inst["system"])
        t0 = time.perf_counter()
        refs.append(_scalar_wcrts(system, inst["deadlines"]))
        if collect_time:
            inst["scalar_time"] = time.perf_counter() - t0
    return refs


# --- comparison -------------------------------------------------------------

def _as_matrix(values, n_tasks):
    """Normalize the candidate's return to a list of rows of length ``n_tasks``."""
    # Accept list-of-lists or numpy arrays (duck-typed via .tolist()).
    if hasattr(values, "tolist"):
        values = values.tolist()
    rows = []
    for row in values:
        if hasattr(row, "tolist"):
            row = row.tolist()
        rows.append([float(x) for x in row])
    return rows


def compare(candidate_wcrts, reference, rtol=1e-6, atol=1e-6):
    """Return ``(ok, stats)`` comparing candidate WCRTs against the reference.

    ``stats`` has ``n`` (values compared), ``mismatches`` (count) and
    ``max_rel`` (largest relative error). Infinite values must match exactly.
    """
    cand = _as_matrix(candidate_wcrts, len(reference[0]) if reference else 0)
    if len(cand) != len(reference):
        return False, {"n": 0, "mismatches": len(reference), "max_rel": float("inf"),
                       "error": f"expected {len(reference)} rows, got {len(cand)}"}
    n = 0
    mism = 0
    max_rel = 0.0
    for crow, rrow in zip(cand, reference):
        if len(crow) != len(rrow):
            return False, {"n": n, "mismatches": mism + 1, "max_rel": float("inf"),
                           "error": f"row length {len(crow)} != {len(rrow)}"}
        for c, r in zip(crow, rrow):
            n += 1
            if r == float("inf") or c == float("inf"):
                if c != r:
                    mism += 1
                continue
            err = abs(c - r) / max(abs(r), 1e-12)
            max_rel = max(max_rel, err)
            if err > rtol and abs(c - r) > atol:
                mism += 1
    return mism == 0, {"n": n, "mismatches": mism, "max_rel": max_rel}


def evaluate(analyze, instances=None, population=25, levels=None, k=100,
             rtol=1e-6, atol=1e-6, verbose=True):
    """Check equivalence and speedup of the candidate ``analyze`` function.

    ``analyze(system, deadlines)`` is called once per instance with the full
    ``(k, n_tasks)`` matrix and must return the ``(k, n_tasks)`` WCRTs (per task,
    in ``system.tasks`` order). Returns a report dict.
    """
    if instances is None:
        instances = build_instances(population=population, levels=levels, k=k)
    references = reference_wcrts(instances, collect_time=True)

    total_scalar = sum(i["scalar_time"] for i in instances)
    total_candidate = 0.0
    all_ok = True
    worst_rel = 0.0
    total_n = 0
    total_mism = 0
    per_instance = []
    for inst, ref in zip(instances, references):
        system = deepcopy(inst["system"])
        t0 = time.perf_counter()
        try:
            got = analyze(system, inst["deadlines"])
            candidate_time = time.perf_counter() - t0
            ok, stats = compare(got, ref, rtol=rtol, atol=atol)
        except Exception as exc:
            ok, stats, candidate_time = False, {"n": 0, "mismatches": -1,
                                                "max_rel": float("inf"),
                                                "error": f"{type(exc).__name__}: {exc}"}, 0.0
        total_candidate += candidate_time
        all_ok &= ok
        worst_rel = max(worst_rel, stats.get("max_rel", float("inf")))
        total_n += stats.get("n", 0)
        total_mism += stats.get("mismatches", 0)
        per_instance.append({"name": inst["name"], "ok": ok,
                             "scalar_time": inst["scalar_time"],
                             "candidate_time": candidate_time,
                             "stats": stats})
        if verbose:
            flag = "OK " if ok else "FAIL"
            detail = "" if ok else f"  {stats.get('error', '')} mismatches={stats.get('mismatches')}"
            print(f"  [{flag}] {inst['name']:16s} "
                  f"scalar={inst['scalar_time']*1e3:8.2f}ms "
                  f"cand={candidate_time*1e3:8.2f}ms "
                  f"max_rel={stats.get('max_rel', float('inf')):.2e}{detail}", flush=True)

    speedup = total_scalar / total_candidate if total_candidate > 1e-12 else float("nan")
    return {
        "ok": all_ok,
        "instances": len(instances),
        "values": total_n,
        "mismatches": total_mism,
        "max_rel": worst_rel,
        "scalar_time": total_scalar,
        "candidate_time": total_candidate,
        "speedup": speedup,
        "per_instance": per_instance,
    }
