"""Holistic local-EDF analysis (vendored, read-only).

This is the **scalar reference**: for one system with one set of local deadlines
it computes the worst-case response times (WCRTs) that your vectorized analysis
must reproduce — same values, but for a whole batch of assignments at once. It is
**approximate, not exact** (it is not a perfect oracle for the real system), but
it is the reference for this lab: your output must match *this* analysis
value for value.

The analysis is *holistic*: because tasks in a flow execute on different
processors, the release jitter of a task equals the worst-case response time of
its predecessor. Tasks on a processor are scheduled by **local EDF**, so
interference depends on the absolute-deadline points (the set ``psi``) rather
than on a priority ordering. The parameter is each task's **local deadline**
(``task.deadline``).

Do not edit this file.
"""

import math
import time

from .model import init_wcrt, reset_wcrt


class LimitFactorReachedException(Exception):
    def __init__(self, task, response_time, limit):
        self.task = task
        self.response_time = response_time
        self.limit = limit
        super().__init__(
            f"response time of {task.name} (R={response_time}) reached the "
            f"limit (limit={limit})")


class HolisticLocalEDFAnalysis:
    """Compute worst-case response times of a local-EDF system (in ``task.wcrt``).

    Parameters
    ----------
    limit_factor:
        A provisional response time above ``flow.deadline * limit_factor``
        aborts the analysis for that task; larger values trade speed for
        precision.
    reset:
        If True, ``task.wcrt`` is reset to ``None`` before the analysis.
    verbose:
        Print when the analysis aborts.
    max_time:
        Optional wall-clock budget (seconds); exceeding it behaves like
        reaching the response-time limit.
    """

    def __init__(self, limit_factor=10, reset=True, verbose=False, max_time=None):
        self.limit_factor = limit_factor
        self.reset = reset
        self.verbose = verbose
        self.max_time = max_time
        self._start = None

    def __call__(self, system):
        return self.apply(system)

    @staticmethod
    def _wi(task, t: float, D: float) -> float:
        """Eq (1)"""
        pl = math.ceil((t + task.jitter) / task.period)
        pd = 0 if D < task.deadline else math.floor((task.jitter + D - task.deadline) / task.period) + 1
        m = min(pl, pd)
        return m * task.wcet if m > 0 else 0

    @classmethod
    def _busy_period(cls, task, l_prev: float) -> float:
        """Eq (5) [adapted from Mast implementation]"""
        own = math.ceil(l_prev / task.period) * task.wcet
        tasks = [t for t in task.processor.tasks if t != task]
        length = own + sum(math.ceil((l_prev + t.jitter) / t.period) * t.wcet
                           for t in tasks)
        if math.isclose(length, l_prev):
            return length
        return cls._busy_period(task, length)

    @classmethod
    def _build_set_psi_ij(cls, task, busy_period: float):
        # eq (4) -- release points of interfering tasks
        tasks = [t for t in task.processor.tasks if t != task]
        psi_ij = {(q - 1) * t.period - t.jitter + t.deadline
                  for t in tasks
                  for q in range(1, math.ceil((busy_period + t.jitter) / t.period) + 1)
                  if (q - 1) * t.period - t.jitter >= 0}
        psi_ij |= {t.deadline for t in tasks}
        return psi_ij

    @classmethod
    def _build_set_psi_ab(cls, task, busy_period: float, p: int):
        # Eq (6) -- release points of the analyzed task for index p
        return {(p - 1) * task.period + task.deadline
                for p in range(1, math.ceil(busy_period / task.period) + 1)}

    @staticmethod
    def _ra(task, psi, wab):
        """Eq (9)"""
        return wab - psi + task.deadline + task.jitter

    @classmethod
    def _wab(cls, task, psi, p, wab_prev):
        """Eq (8)"""
        wab = p * task.wcet + sum(
            cls._wi(t, wab_prev, psi)
            for t in task.processor.tasks if t != task)
        if math.isclose(wab, wab_prev):
            return wab
        return cls._wab(task, psi, p, wab)

    def apply(self, system) -> None:
        init_wcrt(system)
        self._start = time.perf_counter()
        try:
            while True:
                changed = False
                for task in system.tasks:
                    changed |= self._task_analysis(task)
                if not changed:
                    break
        except LimitFactorReachedException as exc:
            if self.verbose:
                print(exc.message)
            if self.reset:
                reset_wcrt(system)
            else:
                exc.task.wcrt = exc.response_time
                for task in exc.task.all_successors:
                    task.wcrt = exc.response_time

    def _task_analysis(self, task) -> bool:
        if self._timeout():
            raise LimitFactorReachedException(task, task.wcrt or 0, float("inf"))
        length = self._busy_period(task, task.wcet)
        max_r = 0
        # psi_ij does not depend on p; compute once and reuse across the p-loop.
        psi_ij = self._build_set_psi_ij(task, length)
        for p in range(1, math.ceil(length / task.period) + 1):
            psi_ab = self._build_set_psi_ab(task, length, p)
            psi_set = {psi for psi in (psi_ij | psi_ab)
                       if (p - 1) * task.period + task.deadline
                       <= psi < p * task.period + task.deadline}
            for psi in psi_set:
                w = self._wab(task, psi, p, p * task.wcet)
                r = self._ra(task, psi, w)
                if r > max_r:
                    max_r = r
                if self._timeout() or r > task.flow.deadline * self.limit_factor:
                    raise LimitFactorReachedException(
                        task, max_r, task.flow.deadline * self.limit_factor)

        if max_r > task.wcrt:
            task.wcrt = max_r
            return True
        return False

    def _timeout(self) -> bool:
        return self.max_time is not None and time.perf_counter() - self._start > self.max_time
